import esbuild from "esbuild";
import { copyFileSync, existsSync, mkdirSync, readFileSync, watch, writeFileSync } from "node:fs";
import { builtinModules } from "node:module";
import { join } from "node:path";
import process from "node:process";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

// Local test vault: OBSIDIAN_VAULT env var, or the first line of a gitignored
// `.obsidian-vault` file. Never used in CI.
function resolveVault() {
	if (process.env.CI) return null;
	const fromEnv = process.env.OBSIDIAN_VAULT?.trim();
	if (fromEnv) return fromEnv;
	if (existsSync(".obsidian-vault")) {
		const fromFile = readFileSync(".obsidian-vault", "utf8").split(/\r?\n/)[0].trim();
		if (fromFile) return fromFile;
	}
	return null;
}

const vault = resolveVault();
const pluginId = JSON.parse(readFileSync("manifest.json", "utf8")).id;
const PLUGIN_FILES = ["main.js", "manifest.json", "styles.css"];

const copyToVault = {
	name: "copy-to-vault",
	setup(build) {
		if (!vault) return;
		if (!existsSync(join(vault, ".obsidian"))) {
			console.warn(`[copy-to-vault] ${vault} has no .obsidian folder; is it a vault? Skipping copy.`);
			return;
		}
		const target = join(vault, ".obsidian", "plugins", pluginId);
		if (!prod) {
			// esbuild only watches the TS graph; push CSS-only edits too.
			watch("styles.css", () => {
				mkdirSync(target, { recursive: true });
				copyFileSync("styles.css", join(target, "styles.css"));
				console.log(`[copy-to-vault] styles.css → ${target}`);
			});
		}
		build.onEnd((result) => {
			if (result.errors.length > 0) return;
			mkdirSync(target, { recursive: true });
			for (const file of PLUGIN_FILES) copyFileSync(file, join(target, file));
			// Lets the Hot Reload community plugin reload YTranscript automatically.
			if (!prod) writeFileSync(join(target, ".hotreload"), "");
			console.log(`[copy-to-vault] ${PLUGIN_FILES.join(", ")} → ${target}`);
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/obsidian/plugin.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	define: {
		global: "globalThis",
	},
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	plugins: [copyToVault],
});

if (prod) {
	try {
		await context.rebuild();
	} catch {
		process.exit(1);
	}
	await context.dispose();
} else {
	await context.watch();
}
